# ── Output schema ────────────────────────────────────────────────────
#
# v2 CHANGE: contentText (single string) -> bullets (array).
#
# v1's schema forced every role's achievements into one string, which is
# why real output compressed a 15-bullet role into a single paragraph.
# The v1 experience prompt asked for "bullet points" (plural) while the
# schema could only hold one blob — the prompt and the schema
# contradicted each other, and the schema won.
#
# Per-bullet evidenceIndexes also makes verification STRICTER, not
# looser: each claim must independently cite and pass the evidence
# check, instead of one citation list covering a whole paragraph.
#
# Downstream callers must be updated: generation_core.py reads
# result.data["contentText"], and evidence_binder verification runs per
# section. Both need to iterate bullets. The summary task legitimately
# stays single-string — see SUMMARY_JSON_SCHEMA below.

_BULLETS_JSON_SCHEMA = {
    "type": "object",
    "properties": {
        "bullets": {
            "type": "array",
            "minItems": 1,
            "maxItems": 6,
            "items": {
                "type": "object",
                "properties": {
                    "text": {"type": "string"},
                    "evidenceIndexes": {"type": "array", "items": {"type": "integer"}},
                },
                "required": ["text", "evidenceIndexes"],
                "additionalProperties": False,
            },
        },
    },
    "required": ["bullets"],
    "additionalProperties": False,
}

# The summary is genuinely one continuous piece of prose, not a bullet
# list, so it keeps the v1 single-string shape rather than being forced
# into the bullets structure for symmetry's sake.
SUMMARY_JSON_SCHEMA = {
    "type": "object",
    "properties": {
        "contentText": {"type": "string"},
        "evidenceIndexes": {"type": "array", "items": {"type": "integer"}},
    },
    "required": ["contentText", "evidenceIndexes"],
    "additionalProperties": False,
}

EXPERIENCE_BULLET_JSON_SCHEMA = dict(_BULLETS_JSON_SCHEMA)
