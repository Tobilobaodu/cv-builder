"""Versioned prompt templates for tailored CV generation.

System-prompt text only — CV content, job-post content, and user
instructions never appear here (10-security-plan.md §5's instruction/data
separation requirement: they're assembled into the *user* message by
build_user_payload(), always framed as untrusted data). Each template has
an explicit PROMPT_VERSION string written to
tailored_cv_sections.prompt_version, so a future wording change doesn't
silently change the provenance record of content already generated
under the old version.

v2 CHANGE LOG
-------------
v1 contained comprehensive non-fabrication rules and essentially no
writing-quality guidance. Audit of real v1 output against the original
source CV found the model's rewrites were measurably *worse* than the
candidate's own prose:

  - AI-flagged term density: 0.23 per 100 words (source CV)
                          → 3.96 per 100 words (v1 output), a 17x rise
  - "Hands on design lead"  → "Served as the hands-on design lead"
  - "improve digital journeys" → "enhance digital user journeys"
  - "surface customer needs and uncover conversion opportunities"
        → "identify customer needs, leading to opportunities for
           conversion enhancement"
  - First-person leakage into bullets ("My contributions led to...")
  - UK source spelling silently Americanised (optimisation → optimization)

v2 adds WRITING_STANDARDS and ANTI_AI_TELL_RULES. The non-fabrication
rules are unchanged — they were never the problem.
"""

